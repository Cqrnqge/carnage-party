const RECENT_KEY = 'carnage_recent_emojis';

function loadRecent() {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY) || '[]').slice(0, 20);
  } catch {
    return [];
  }
}

export default function EmojiPicker({ onPick, onClose, className = '' }) {
  const [tab, setTab] = useState('smileys');
  const [query, setQuery] = useState('');
  const [recent, setRecent] = useState(loadRecent);
  const ref = useRef(null);
  const inputRef = useRef(null);

  useEffect(() => {
    const onDown = (event) => {
      if (ref.current && !ref.current.contains(event.target)) onClose?.();
    };
    const onKey = (event) => {
      if (event.key === 'Escape') onClose?.();
    };
    document.addEventListener('mousedown', onDown);
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('mousedown', onDown);
      document.removeEventListener('keydown', onKey);
    };
  }, [onClose]);

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return null;
    const all = [];
    for (const group of GROUPS) {
      for (const emoji of group.emojis) {
        const keywords = KEYWORDS[emoji] || '';
        if (emoji.includes(q) || keywords.includes(q) || group.name.toLowerCase().includes(q)) {
          all.push(emoji);
        }
      }
    }
    return [...new Set(all)].slice(0, 120);
  }, [query]);

  const pick = (emoji) => {
    const next = [emoji, ...recent.filter((item) => item !== emoji)].slice(0, 20);
    setRecent(next);
    try { localStorage.setItem(RECENT_KEY, JSON.stringify(next)); } catch {}
    onPick?.(emoji);
  };

  const group = GROUPS.find((g) => g.id === tab) || GROUPS[0];
  const emojis = filtered || (tab === 'recent' ? recent : group.emojis);

  return (
    <div ref={ref} className={cx('emoji-picker', className)}>
      <div className="emoji-head">
        <div className="emoji-search">
          <Search size={14} />
          <input
            ref={inputRef}
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Поиск эмодзи…"
            autoFocus
          />
          {query ? (
            <button className="icon-btn tiny" onClick={() => setQuery('')} aria-label="Очистить">
              <X size={13} />
            </button>
          ) : null}
        </div>
        <button className="icon-btn tiny" onClick={onClose} aria-label="Закрыть">
          <X size={15} />
        </button>
      </div>
      <div className="emoji-tabs">
        {recent.length ? (
          <button className={cx('emoji-tab', tab === 'recent' && 'active')} onClick={() => { setTab('recent'); setQuery(''); }} title="Недавние">
            🕘
          </button>
        ) : null}
        {GROUPS.map((g) => (
          <button
            key={g.id}
            className={cx('emoji-tab', tab === g.id && !query && 'active')}
            onClick={() => { setTab(g.id); setQuery(''); }}
            title={g.name}
          >
            {g.icon}
          </button>
        ))}
      </div>
      <div className="emoji-group-name">
        {filtered ? 'Результаты поиска' : tab === 'recent' ? 'Недавние' : group.name}
      </div>
      <div className="emoji-grid">
        {emojis.length === 0 ? <div className="emoji-empty">Ничего не найдено</div> : null}
        {emojis.map((emoji, index) => (
          <button key={`${emoji}-${index}`} className="emoji-cell" onClick={() => pick(emoji)} title={KEYWORDS[emoji] || emoji}>
            {emoji}
          </button>
        ))}
      </div>
      <div className="emoji-footer">
        <Smile size={14} />
        <span>Нажмите на эмодзи, чтобы вставить</span>
      </div>
    </div>
  );
}
